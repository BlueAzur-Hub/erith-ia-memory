"use strict";
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const assert=require("node:assert/strict");
const code=fs.readFileSync(path.resolve(__dirname,"../public/agent_crypto_erith_ia/administrator/js/graph-native-usd-406520.js"),"utf8");
const ctx={console};ctx.globalThis=ctx;vm.runInNewContext(code,ctx,{filename:"graph-native-usd-406520.js"});
const api=ctx.AgentCryptoGraphNativeUsd406520;
assert.equal(typeof api.usdTooltipSource,"function");
const now=Date.UTC(2025,7,12,12,0,0);
const freshCoin={id:"example-token",priceUsd:15,change24h:0.6,
  lastUpdated:new Date(now-90000).toISOString()};
const label=c=>api.usdTooltipSource(c,now);
const fresh=label({dataset:{atlasCoin:freshCoin}});
assert.equal(fresh.source,"coingecko-usd-snapshot");
assert.match(fresh.label,/COINGECKO USD/);
assert.doesNotMatch(fresh.label,/LIVE BINANCE|SOURCE NON CONFIRMÉE/);
const missing=label({dataset:{}});
assert.equal(missing.source,"unknown");
assert.doesNotMatch(missing.label,/COINGECKO|BINANCE/);
const unqualified=label({dataset:{atlasCoin:{id:"example-token",priceUsd:null,change24h:null}}});
assert.equal(unqualified.source,"unknown");
const stale=label({dataset:{atlasCoin:{...freshCoin,lastUpdated:new Date(now-3600000).toISOString()}}});
assert.equal(stale.source,"coingecko-stale");
assert.match(stale.label,/ANCIEN/);
const future=label({dataset:{atlasCoin:{...freshCoin,lastUpdated:new Date(now+120000).toISOString()}}});
assert.equal(future.source,"coingecko-stale");
const undated=label({dataset:{atlasCoin:{...freshCoin,lastUpdated:undefined}}});
assert.equal(undated.source,"coingecko-undated");
assert.doesNotMatch(undated.label,/SNAPSHOT COINGECKO USD · \d/);
assert(code.includes('root.dataset.priceSource=quoteSource.source'));
assert(!code.includes('"PRIX INDICATIF · SOURCE NON CONFIRMÉE"'));
const ct=fs.readFileSync(path.resolve(__dirname,"../public/agent_crypto_erith_ia/trader/trader-okx-account.js"),"utf8");
assert.match(ct,/indicative_difference_usdc\.toLocaleString\('fr-FR',\{maximumFractionDigits:8\}\)/);
assert.equal((0.2637204899999999).toLocaleString("fr-FR",{maximumFractionDigits:8}),"0,26372049");
console.log("BTC/USD tooltip source qualification and CT decimal display PASS");

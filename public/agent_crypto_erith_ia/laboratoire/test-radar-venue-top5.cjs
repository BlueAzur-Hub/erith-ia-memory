/* Seven Heaven Top 5 continuity: deterministic offline tests over canonical repository archives. */
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {compile,selectRows}=require("./radar-venue-top5.js");
const archive=path.join(__dirname,"../data/historical_archive_prototype");
const matrix=JSON.parse(fs.readFileSync(path.join(archive,"cross_venue_gap_matrix/index.json"),"utf8"));
const incidents=JSON.parse(fs.readFileSync(path.join(archive,"exchange_incident_register/index.json"),"utf8"));
const result=compile(matrix,incidents);
assert.equal(result.schema,"seven.venue.top5.readonly.v1");
assert.equal(result.entries.length,42);
assert.deepEqual(result.counts,{BTC:27,ETH:4,BNB:4,XRP:4,SOL:3});
assert.equal(result.ordersEnabled,false);
assert.equal(result.paperExecutionsProven,0);
assert.equal(result.quoteSubstitution,false);
assert.equal(selectRows(result,{asset:"ETH"}).length,4);
assert.equal(selectRows(result,{date:"2021-08-13"}).length,5);
assert.equal(selectRows(result,{proof:"unknown"}).length,1);
assert.equal(selectRows(result,{proof:"official"}).length,41);
assert.equal(selectRows(result,{proof:"complete"}).length,34);
assert.equal(selectRows(result,{proof:"partial"}).length,1);
assert.equal(selectRows(result,{proof:"suspended"}).length,3);
assert.equal(selectRows(result,{proof:"none"}).length,4);
const unknown=selectRows(result,{proof:"unknown"})[0];
assert.equal(unknown.asset,"BTC");
assert.equal(unknown.date,"2019-11-13");
assert.equal(unknown.incidentUrl,null);
assert.match(unknown.binanceNote,/ZIP natif BTC/);
const xrp=selectRows(result,{asset:"XRP",date:"2021-08-13"})[0];
assert.equal(xrp.coinbaseCoverage,"NOT_QUERIED_SUSPENDED");
assert.equal(xrp.coinbaseCandles,0);
assert.deepEqual(xrp.coinbaseRequestUrls,[]);
assert.equal(xrp.krakenQuote,"USD");
const sol=selectRows(result,{asset:"SOL",date:"2021-08-13"})[0];
assert.equal(sol.coinbaseCoverage,"PARTIAL");
assert.equal(sol.coinbaseCandles,269);
assert.equal(sol.minutes,270);
for(const row of result.entries) {
 assert.equal(row.binanceQuote,"USDT");
 assert.equal(row.coinbaseQuote,"USD");
 assert.equal(row.paperExecutionsProven,0);
 assert.equal(row.alternativeCandlesUsableAsBinance,false);
 assert.ok(row.coinbasePositive<=row.coinbaseCandles);
 assert.ok(Number.isFinite(Date.parse(row.start)));
 assert.ok(Number.isFinite(Date.parse(row.end)));
 assert.ok(row.end>row.start);
}
assert.ok(selectRows(result,{venue:"kraken"}).every(x=>x.krakenPositive>0));
assert.ok(selectRows(result,{venue:"coinbase"}).every(x=>x.coinbasePositive>0));
assert.ok(selectRows(result,{venue:"binance"}).every(x=>x.binanceClass==="OFFICIAL_BTC_WINDOW"));
const html=fs.readFileSync(path.join(__dirname,"venue-continuity.html"),"utf8");
assert.match(html,/radar-venue-continuity\.js/);
assert.match(html,/radar-venue-top5\.js/);
for(const id of ["top5-asset","top5-date","top5-venue","top5-proof","top5-evidence-rows","top5-evidence-status"])assert.ok(html.includes('id="'+id+'"'));

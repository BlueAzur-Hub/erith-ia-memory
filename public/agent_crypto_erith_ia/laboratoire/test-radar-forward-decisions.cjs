"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),crypto=require("node:crypto"),path=require("node:path");
const {audit,CONTRACT}=require("./radar-forward-decisions.js");
const ROOT=path.resolve(__dirname,"../data/trader_flux/radar20_forward");
const indexBytes=fs.readFileSync(path.join(ROOT,"index.json")),index=JSON.parse(indexBytes);

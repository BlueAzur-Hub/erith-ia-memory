assert.equal(r.windows.slice(4).reduce((n,w)=>n+w.B,0),4);
assert.equal(r.windows[4].eligible,82);
assert.equal(r.events.length,444);
assert.equal(r.real_orders,0);
assert.equal(r.orders_enabled,false);
assert.equal(r.not_a_signal,true);
assert.ok(r.events.some(e=>e.after_4h_pct===null),"Late observations must not invent later prices");
assert.ok(r.events.some(e=>e.after_24h_pct!==null),"Measured +24h must exist where archived");
assert.ok(r.events.every(e=>e.at_utc>="2026-10-17T01:00:00Z"));
assert.ok(r.events.every(e=>["accepted","filter","existing","capacity","cash"].includes(e.A)));
assert.ok(r.events.every(e=>["accepted","filter","existing","capacity","cash"].includes(e.B)));
